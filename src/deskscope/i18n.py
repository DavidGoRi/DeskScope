def pick_language(cookie: str | None, accept_language: str | None) -> str:
    """Language from the cookie, else the browser's preference, else English."""
    if cookie in LANGUAGES:
        return cookie
    for part in (accept_language or "").split(","):
        code = part.split(";")[0].strip().lower()[:2]
        if code in LANGUAGES:
            return code
    return DEFAULT_LANGUAGE


def translate(lang: str, key: str, **params: object) -> str:
    table = MESSAGES.get(lang, MESSAGES[DEFAULT_LANGUAGE])
    text = table.get(key) or MESSAGES[DEFAULT_LANGUAGE].get(key) or key
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError):
            return text
    return text
